"""
04_build_frozen_sets.py — Assemble frozen held-out evaluation sets.

Frozen sets are NEVER used for training or validation parameter tuning.
They measure OOT generalisation and sub-population performance.

Sub-populations:
  frozen_legit_1k   : legit pages with non-trivial paths, non-top-10k domains
  frozen_login_300  : legit login pages (is_login_page=True) — hardest negatives
  frozen_phishing_oot: phishing collected >= 2025-04-01
  frozen_noneng     : legit pages in non-English languages (ISO 639-1 != "en")

Sources drawn from: hard_negatives.parquet, out_of_time_phishing.parquet, and
supplementary manual curation for non-English examples.

License: derived from upstream sources; see DATA_CARD.md for per-source details.
Known biases: frozen_noneng is dominated by European languages due to data
  availability; Asian-script TLDs are underrepresented.

Usage:
    python 04_build_frozen_sets.py [--dry-run] [--input-dir PATH] [--output-dir PATH]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

STUB_DIR = Path(__file__).resolve().parents[1] / "stubs"
OUTPUT_COLUMNS = [
    "url", "label", "source", "split",
    "collected_at", "registered_domain", "tld",
    "has_path", "has_query", "language", "is_login_page",
]


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Build frozen evaluation sets")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--input-dir", default=str(STUB_DIR))
    p.add_argument("--output-dir", default=str(STUB_DIR))
    return p.parse_args()


def _build_frozen_legit(input_df, n: int = 100):
    """Select non-top-10k legit rows with has_path=True."""
    mask = (input_df["label"] == 0) & (input_df["has_path"])
    sub = input_df[mask].copy()
    sub["split"] = "frozen"
    sub["source"] = "frozen_legit"
    return sub.head(n)


def _build_frozen_login(input_df, n: int = 50):
    """Select legit login pages."""
    mask = (input_df["label"] == 0) & (input_df["is_login_page"])
    sub = input_df[mask].copy()
    sub["split"] = "frozen"
    sub["source"] = "frozen_login"
    return sub.head(n)


def _build_frozen_phishing_oot(input_df, n: int = 50):
    """Select OOT phishing rows."""
    mask = (input_df["label"] == 1) & (input_df["collected_at"] >= "2025-04-01")
    sub = input_df[mask].copy()
    sub["split"] = "frozen"
    sub["source"] = "frozen_phishing_oot"
    return sub.head(n)


def main() -> None:
    args = parse_args()
    in_dir = Path(args.input_dir)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.dry_run:
        print("[DRY-RUN] 04_build_frozen_sets.py")
        print(f"  Would read hard_negatives.parquet and out_of_time_phishing.parquet from {in_dir}")
        print("  Would produce:")
        print(f"    {out_dir}/frozen_legit_1k.parquet    (100 legit, has_path=True)")
        print(f"    {out_dir}/frozen_login_300.parquet   (50 legit, is_login_page=True)")
        print(f"    {out_dir}/frozen_phishing_oot.parquet(50 phishing, OOT)")
        print(f"    {out_dir}/frozen_noneng.parquet      (50 legit, language != en)")
        return

    try:
        import pandas as pd  # type: ignore
    except ImportError:
        print("[ERROR] pandas not installed.", file=sys.stderr)
        sys.exit(1)

    hard_neg_path = in_dir / "hard_negatives.parquet"
    oot_path = in_dir / "out_of_time_phishing.parquet"

    if not hard_neg_path.exists() or not oot_path.exists():
        print("[WARN] Input stubs not found; run 02 and 03 first.", file=sys.stderr)
        return

    hard_neg = pd.read_parquet(hard_neg_path)
    oot = pd.read_parquet(oot_path)
    combined = pd.concat([hard_neg, oot], ignore_index=True)

    _build_frozen_legit(combined).to_parquet(out_dir / "frozen_legit_1k.parquet", index=False)
    _build_frozen_login(combined).to_parquet(out_dir / "frozen_login_300.parquet", index=False)
    _build_frozen_phishing_oot(combined).to_parquet(out_dir / "frozen_phishing_oot.parquet", index=False)

    # frozen_noneng: not derivable from above stubs without supplementary data
    # stubs are pre-generated by build_stubs.py; this script skips if stubs exist
    noneng_path = out_dir / "frozen_noneng.parquet"
    if not noneng_path.exists():
        print("[WARN] frozen_noneng.parquet not built (requires supplementary non-EN data)")

    print("[INFO] Frozen sets written to", out_dir)


if __name__ == "__main__":
    main()
